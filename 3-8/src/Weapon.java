public class Weapon {
    String name = "ブロンズソード";
    int power = 10;
    public Weapon(String name, int power){
        this.name = name;
        this.power = power;

    }
    public String getName(){
        return this.name;
    
    }
    public int getPower(){
        return this.power;
        
    }

    
}
